"""End-to-end test of the Flutter web build in real Chrome against the REAL
Cloud Firestore project, plus output screenshots.

Usage (from the project root, after `flutter build web`):
    python tool/e2e_chrome_test.py screenshots [--reset]

--reset deletes all documents in `employees` first (so the empty state
can be captured). Do not use it once the collection holds real data.

Each browser launch uses a brand-new Chrome profile (no cache, no local
storage), so anything shown after a relaunch must have come from Firestore.
Server-side state is double-checked through the Firestore REST API.
"""
import json, os, subprocess, sys, time, urllib.request
from playwright.sync_api import sync_playwright, expect

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PORT = 8777
URL = f"http://127.0.0.1:{PORT}/"
ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
RESET = "--reset" in sys.argv
SHOTS = os.path.abspath(ARGS[0] if ARGS else "screenshots")
os.makedirs(SHOTS, exist_ok=True)

# Real project config generated by `flutterfire configure`.
opts = open(os.path.join(ROOT, "lib", "firebase_options.dart"), encoding="utf-8").read()
PROJECT = opts.split("projectId: '")[1].split("'")[0]
API_KEY = opts.split("static const FirebaseOptions web")[1].split("apiKey: '")[1].split("'")[0]
REST = (f"https://firestore.googleapis.com/v1/projects/{PROJECT}"
        f"/databases/(default)/documents/employees")

EMPLOYEES = [("Suresh", "2345", "67000"), ("bright", "781", "60000"),
             ("Joel", "891", "78000")]
EXTERNAL = ("Victor", 890, 40000)  # written outside the app (like Firebase Console)


def step(msg):
    print(msg, flush=True)


def rest_list():
    with urllib.request.urlopen(f"{REST}?key={API_KEY}&pageSize=300") as r:
        docs = json.load(r).get("documents", [])
    out = []
    for d in docs:
        f = d["fields"]
        out.append((f["name"]["stringValue"], int(f["empid"]["integerValue"]),
                    int(f["salary"]["integerValue"])))
    return sorted(out)


def rest_add(name, empid, salary):
    body = json.dumps({"fields": {"name": {"stringValue": name},
                                  "empid": {"integerValue": str(empid)},
                                  "salary": {"integerValue": str(salary)}}}).encode()
    req = urllib.request.Request(f"{REST}?key={API_KEY}", data=body, method="POST",
                                 headers={"Content-Type": "application/json"})
    urllib.request.urlopen(req).read()


def rest_clear():
    """Delete every document in `employees` (test data only; --reset flag)."""
    with urllib.request.urlopen(f"{REST}?key={API_KEY}&pageSize=300") as r:
        docs = json.load(r).get("documents", [])
    for d in docs:
        url = f"https://firestore.googleapis.com/v1/{d['name']}?key={API_KEY}"
        urllib.request.urlopen(urllib.request.Request(url, method="DELETE")).read()
    return len(docs)


def launch(p, viewport=(1280, 860)):
    browser = p.chromium.launch(channel="chrome", headless=True)
    ctx = browser.new_context(viewport={"width": viewport[0], "height": viewport[1]})
    page = ctx.new_page()
    page.on("console", lambda m: m.type == "error" and print("CONSOLE:", m.text))
    return browser, page


def open_app(page):
    page.goto(URL)
    page.wait_for_selector("flt-semantics-placeholder", state="attached", timeout=60000)
    page.locator("flt-semantics-placeholder").dispatch_event("click")
    expect(page.get_by_role("button", name="Save Details")).to_be_visible(timeout=30000)
    page.wait_for_timeout(800)


def text(page, value):
    # Only the visible semantics tree, not Flutter's screen-reader announcements.
    return page.locator("flt-semantics-host").get_by_text(value)


def box(page, label):
    return page.get_by_role("textbox", name=label)


def fill(page, name, empid, salary):
    for label, value in (("Enter your Name", name), ("Enter your EmpID", empid),
                         ("Enter your Salary", salary)):
        box(page, label).click()
        page.wait_for_timeout(250)  # let Flutter move focus before typing
        page.keyboard.type(value, delay=15)
        expect(box(page, label)).to_have_value(value)


def save(page):
    page.get_by_role("button", name="Save Details").click()


def shot(page, name):
    page.screenshot(path=os.path.join(SHOTS, name))
    step(f"   screenshot -> screenshots/{name}")


def main():
    server = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT),
                               "--directory", os.path.join(ROOT, "build", "web")],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    time.sleep(1.5)
    try:
        if RESET:
            step(f"--reset: deleted {rest_clear()} existing test documents")
        before = rest_list()
        step(f"Firestore project {PROJECT}: employees collection has {len(before)} docs before test")

        with sync_playwright() as p:
            browser, page = launch(p)
            open_app(page)

            step("TEST 1  Read on empty collection shows 'No Employees Found'")
            if not before:
                expect(text(page, "No Employees Found")).to_be_visible(timeout=30000)
                shot(page, "01_empty_state.png")
            else:
                step("   skipped (collection not empty)")

            step("TEST 2  Validation of empty fields")
            save(page)
            for msg in ("Please enter your name", "Please enter your Employee ID",
                        "Please enter your salary"):
                expect(text(page, msg)).to_be_visible()
            assert rest_list() == before, "nothing must be written when invalid"
            shot(page, "02_validation_errors.png")

            step("TEST 3  Save one employee (Create)")
            fill(page, *EMPLOYEES[0])
            save(page)
            expect(text(page, "Data Saved Successfully")).to_be_visible(timeout=30000)
            # Form clearing is asserted in test/widget_test.dart; on web the hidden
            # accessibility <input> keeps its old value until refocused, so it
            # is checked visually in the screenshot instead.
            expect(text(page, "EMPID: 2345 SALARY:67000")).to_be_visible(timeout=30000)
            shot(page, "03_employee_saved.png")

            step("TEST 4  Save multiple employees + retrieve all (Read)")
            for e in EMPLOYEES[1:]:
                fill(page, *e)
                save(page)
                expect(text(page, f"EMPID: {e[1]} SALARY:{e[2]}")).to_be_visible(timeout=30000)
            shot(page, "04_multiple_employees.png")

            step("   verifying on Firestore server via REST API")
            server_docs = rest_list()
            for name, empid, salary in EMPLOYEES:
                assert (name, int(empid), int(salary)) in server_docs, f"{name} not in Firestore"
            step(f"   server has: {server_docs}")
            browser.close()

            step("TEST 5  Close and reopen (fresh browser profile, no local cache)")
            browser, page = launch(p)
            open_app(page)
            for name, empid, salary in EMPLOYEES:
                expect(text(page, f"EMPID: {empid} SALARY:{salary}")).to_be_visible(timeout=30000)
            shot(page, "05_after_reopen_persisted.png")

            step("TEST 6  Real-time update: add a document outside the app")
            rest_add(*EXTERNAL)
            expect(text(page, f"EMPID: {EXTERNAL[1]} SALARY:{EXTERNAL[2]}")).to_be_visible(timeout=30000)
            step("   appeared in the open app without reload")
            shot(page, "06_realtime_update.png")
            browser.close()

            step("TEST 7  Responsive layout (phone-size window)")
            browser, page = launch(p, viewport=(412, 915))
            open_app(page)
            expect(text(page, "EMPID: 2345 SALARY:67000")).to_be_visible(timeout=30000)
            shot(page, "07_mobile_layout.png")
            browser.close()

        step(f"Firestore now has {len(rest_list())} employee documents.")
        step("ALL E2E TESTS PASSED")
    finally:
        server.terminate()


if __name__ == "__main__":
    main()
